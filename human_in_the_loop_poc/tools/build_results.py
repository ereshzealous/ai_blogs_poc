"""Generate docs/source/report.src.md, the T3 Run Report, from the published run directory.

    python3 tools/build_results.py          (then tools/build_docs.py builds it with the other documents)

Every value is read from hitl_poc/evidence/runs/<published>/: tables from experiments.json and checks.jsonl, headline
numbers as {{fact}} tokens so the builder records where they are used.  The build stops if an invariant or
implementation check failed (a hypothesis that was not supported is reported, not hidden), or if a scenario's audit
chain does not verify.
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
POC = ROOT / "hitl_poc"
EV = POC / "evidence"
_pub = EV / "published.json"
RUN_ID = json.loads(_pub.read_text())["run_id"] if _pub.exists() else ""
if not (EV / "runs" / RUN_ID / "story.json").exists():
    RUN_ID = sorted(p.parent.name for p in (EV / "runs").glob("*/story.json"))[-1]
RUN = EV / "runs" / RUN_ID
REL = f"hitl_poc/evidence/runs/{RUN_ID}"


def table(head: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c).replace("|", "/") for c in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    ex = json.loads((RUN / "experiments.json").read_text())
    checks = [json.loads(l) for l in (RUN / "checks.jsonl").read_text().splitlines()]
    man = json.loads((RUN / "manifest.json").read_text())
    res = json.loads((RUN / "results.json").read_text())
    story = json.loads((RUN / "story.json").read_text())
    broken = [c["id"] for c in checks if c["status"] == "FAIL" and c["kind"] in ("invariant", "implementation", "control")]
    if broken:
        raise SystemExit(f"build_results: guarantee checks failed {broken}; the report is not generated for a failing run")
    chains = [s["id"] + "/" + a for s in ex["scenarios"] for a, v in s["arms"].items() if not v["metrics"].get("audit_chain_intact")]
    if chains:
        raise SystemExit(f"build_results: audit chain does not verify in {chains}")
    pre = man["preregistration"]
    devs = [l for l in (RUN / "prereg" / "DEVIATIONS.md").read_text().splitlines() if re.match(r"\| \d+ \|", l)]
    arms = ex["arms"]
    xs = {x["id"]: x for x in res["experiments"]}
    lab = {c["id"]: c.get("label") or c["id"] for c in checks}
    s = [f"""---
title: T3 Run Report: {RUN_ID}
subtitle: What ran, under which frozen criteria, and what every scenario and check observed. Generated from the recorded run directory.
byline: T3 · Production AI Engineering
kicker: Production AI Engineering · T3 · Evidence
filed: {RUN_ID[:10]}
run: Recorded run {RUN_ID}
tags: Evidence, Run report, Human-in-the-Loop
---

## About this report

::: kind RECORDED | generated by tools/build_results.py from {REL}/

This is the forensic record behind both editions. Tables are rendered from `experiments.json` and `checks.jsonl`, and headline numbers come from the run's facts. Nothing here is typed. To see each claim traced to its evidence with a status, read the [Evidence Check](human-in-the-loop-evidence.html). To see what is real code and what is simulated, read [Real vs simulated](human-in-the-loop-real-vs-simulated.html).

**{{{{checks.total}}}} checks: {{{{checks.pass}}}} pass, {{{{checks.expected_failure}}}} expected failures (arm A, the control), {{{{checks.fail}}}} fail.** {{{{design.scenarios}}}} scenarios × {{{{design.arms}}}} arms = {{{{design.scenario_runs}}}} scenario runs, plus {{{{tests.total}}}} conformance tests of arm C ({{{{tests.passed}}}} passed) and an HTTP round trip ({{{{api.calls_ok}}}}/{{{{api.calls}}}} calls as expected).

## What ran

{table(["Arm", "Protocol", "What it does"], [[k, v["title"], v["summary"]] for k, v in arms.items()])}

Held constant across arms: the incident, the proposed action, the simulated Kubernetes, the identity chain, the policy fixture, the human decisions and their minutes, the workflow inputs, the scenarios and the evidence questions. Only the approval protocol and resume behaviour change.

## Preregistration and integrity

{table(["Item", "Value"], [["Run", f"`{RUN_ID}`"], ["Frozen", f"{pre['frozen_at']} (before the first scenario run)"], ["Run started", man["started_at"]],
       ["Python", man["environment"]["python"]], ["Model", man["environment"]["model"]], ["Seed", man["environment"]["seed"]],
       ["Source commit", man["source_commit"]], ["Scenario fixture", f"`sha256 {pre['scenario_fixture_sha256'][:16]}…`"],
       ["Code changed since the freeze", ", ".join(f"`{c}`" for c in pre["code_changed_since_freeze"]) or "none"]]
      + [[f"Frozen `{k}`", f"`sha256 {v[:16]}…`"] for k, v in pre["guarded_sha256"].items()])}

Deviations from the preregistration, as logged in `prereg/DEVIATIONS.md`:

{table(["#", "When (UTC)", "What changed", "Why", "Effect on a check"], [[c.strip() for c in d.strip("|").split("|")] for d in devs]) if devs else "None."}

The run is deterministic: the clock, identities, channel, cluster and humans are simulated and scripted. `uv run hitl verify` reruns every scenario and the conformance suite into a fresh directory and compares every raw file byte for byte.

## Fixed global assertions

The pass criteria for arm C, written before the run. The same counts for A and B are observations.

{table(["Assertion (must be 0 under C)", "A", "B", "C"], [[g.replace("_", " "), arms["A"]["global"][g], arms["B"]["global"][g], arms["C"]["global"][g]]
       for g in ("unauthorized_executions", "mutated_action_bypasses", "successful_approval_replays", "duplicate_external_side_effects", "expired_approval_executions",
                 "ineligible_approver_acceptances", "silent_stale_context_resumes", "audit_reconstruction_gaps")]
      + [["legitimate executions (for scale)", arms["A"]["global"]["legit_executions"], arms["B"]["global"]["legit_executions"], arms["C"]["global"]["legit_executions"]],
         ["writes that reached Kubernetes", arms["A"]["global"]["writes"], arms["B"]["global"]["writes"], arms["C"]["global"]["writes"]],
         ["of which changed state", arms["A"]["global"]["state_changes"], arms["B"]["global"]["state_changes"], arms["C"]["global"]["state_changes"]]])}
"""]
    for xid in [k for k, x in xs.items() if str(x.get("h", "")).startswith("H")]:
        x = xs[xid]
        sc = [r for r in ex["scenarios"] if r["experiment"] == x["h"]]
        s.append(f"""## {x['title']} ({xid})

**Question.** {x['question']} **Invariant.** {x['invariant']}

{x['setup']}

{table(["Scenario", "Class", "A", "B", "C"], [[f"{r['id']} {r['title']}", r["class"],
        *[f"`{r['arms'][a]['metrics']['final_code']}` · writes {r['arms'][a]['metrics']['writes']} · unauthorized {r['arms'][a]['metrics']['unauthorized_executions']}" for a in "ABC"]] for r in sc])}

{table(["Check", "Arm", "Kind", "Expected", "Observed", "Status"], [[f"{lab[c['id']]} ({c['id']})", c.get("arm") or "", c["kind"], c["expected"], c["actual"], c["status"] if c["status"] != "FAIL" else f"**{c['finding']}**"]
        for c in checks if c["experiment"] == xid])}

Evidence: `{REL}/raw/scenarios/{x['h']}*/<arm>/` (scenario.json, audit.jsonl, records.json).
""")
    s.append(f"""## The opening story (H5c), recorded

{table(["Time (UTC)", "What", "Detail"], [[t["time"][11:19], t["what"], t["detail"]] for t in story["timeline"]])}

Revalidation on resume: {", ".join(f"{c['check']} {'✓' if c['ok'] else '✗'}" for c in story["revalidation"])}. Outcome per arm: {"; ".join(f"{a} `{v['code']}` with {v['writes']} rollback(s)" for a, v in story["outcome"].items())}. Not revalidated: {"; ".join(f"{n['what']} {n['at_request']} → {n['at_approval']}" for n in story["not_revalidated"]) or "nothing"}.

## Conformance suite and HTTP surface

{table(["Check", "Description", "Status"], [[f"{lab[c['id']]} ({c['id']})", c["description"], c["status"]] for c in checks if c.get("h") in ("CS", "API")])}

## Failures and qualifications

Hypotheses not supported: {", ".join(lab[c["id"]] for c in checks if c["finding"] == "NOT SUPPORTED") or "none"}. Guarantee checks failed: none (the report is not generated otherwise). Arm A's control checks broke as predicted: {", ".join(lab[c["id"]] for c in checks if c["status"] == "EXPECTED_FAILURE")}.

Check labels read as experiment, arm and number (`H5-B01` is H5's first prediction about arm B; `GA-07` is global assertion 7). Each maps one to one to the contract id in `checks.jsonl` (`T3-R5-C02`), where H<n> is experiment T3-R<n>, GA is T3-R10, CS (conformance) is T3-R11 and API is T3-R12. The qualified findings and what they rest on are in the [Evidence Check](human-in-the-loop-evidence.html).

## Reproduce

```bash
cd hitl_poc && uv sync --group dev
uv run pytest                                      # conformance, unit and H1–H9 tests
uv run hitl proof --run-id {RUN_ID}       # refuses to run if a frozen file changed
uv run hitl verify {RUN_ID}               # schemas, freeze, replay byte for byte, integrity
uv run hitl scenarios H5c                          # one scenario, all three arms, printed
```

## Files behind this report

{table(["File", "sha256"], [[f"`{p.name}`", f"`{hashlib.sha256(p.read_bytes()).hexdigest()[:16]}…`"] for p in sorted(RUN.iterdir()) if p.is_file()])}
""")
    out = ROOT / "docs" / "source" / "report.src.md"
    text = "\n".join(s)
    head, body = text.split("\n---\n", 1)
    out.write_text(head + "\n---\n<!-- generated by tools/build_results.py from the published run; do not edit -->\n" + body)
    print(out.relative_to(ROOT))


if __name__ == "__main__":
    main()
