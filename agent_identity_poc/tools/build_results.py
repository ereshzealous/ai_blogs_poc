"""Generate docs/source/report.src.md, the T1 run report, from the published run directory.

    python3 tools/build_results.py          (then tools/build_docs.py builds it with the other documents)

Every value in the report is read from agent_identity_poc/runs/<PUBLISHED>/; nothing is typed.  Headline numbers use
{{fact}} tokens so the builder records where they are used; tables are rendered from the experiment JSON directly.
The build fails if any check in checks.json did not pass, or if the audit chain in audit.jsonl does not verify.
"""

